package core;

import java.util.*;

public class CYK {

    /** Represents a context‑free grammar in Chomsky Normal Form. */
    public static class Grammar {
        private final Map<String, Integer> ntToId = new HashMap<>();
        private final List<String> idToNt = new ArrayList<>();
        private final List<Production> productions = new ArrayList<>();
        private int startSymbolId = -1;

        /** Production in CNF: either A → a or A → B C */
        private static class Production {
            final int left;               // A
            final boolean isTerminal;     // true if A → a
            final String terminal;        // a (valid when isTerminal)
            final int right1;              // B (valid when !isTerminal)
            final int right2;              // C (valid when !isTerminal)

            Production(int left, String terminal) {
                this.left = left;
                this.isTerminal = true;
                this.terminal = terminal;
                this.right1 = -1;
                this.right2 = -1;
            }

            Production(int left, int right1, int right2) {
                this.left = left;
                this.isTerminal = false;
                this.terminal = null;
                this.right1 = right1;
                this.right2 = right2;
            }
        }

        /** Returns the integer id for a non‑terminal, creating a new one if necessary. */
        private int getOrAddNonTerminal(String nt) {
            return ntToId.computeIfAbsent(nt, k -> {
                int id = idToNt.size();
                idToNt.add(k);
                return id;
            });
        }

        /** Sets the start symbol of the grammar. */
        public void setStartSymbol(String start) {
            startSymbolId = getOrAddNonTerminal(start);
        }

        /** Adds a terminal production A → a . */
        public void addTerminal(String left, String terminal) {
            int leftId = getOrAddNonTerminal(left);
            productions.add(new Production(leftId, terminal));
        }

        /** Adds a binary production A → B C . */
        public void addBinary(String left, String right1, String right2) {
            int leftId = getOrAddNonTerminal(left);
            int r1 = getOrAddNonTerminal(right1);
            int r2 = getOrAddNonTerminal(right2);
            productions.add(new Production(leftId, r1, r2));
        }

        /** Returns the id of the start symbol. */
        public int getStartSymbolId() {
            if (startSymbolId == -1) {
                throw new IllegalStateException("Start symbol not defined.");
            }
            return startSymbolId;
        }

        /** Returns the total number of distinct non‑terminals. */
        public int nonTerminalCount() {
            return idToNt.size();
        }

        /** Pre‑computes reverse lookup tables used by CYK. */
        public ReverseMaps buildReverseMaps() {
            Map<String, Set<Integer>> termToNT = new HashMap<>();
            Map<Pair, Set<Integer>> pairToNT = new HashMap<>();

            for (Production p : productions) {
                if (p.isTerminal) {
                    termToNT.computeIfAbsent(p.terminal, k -> new HashSet<>()).add(p.left);
                } else {
                    Pair key = new Pair(p.right1, p.right2);
                    pairToNT.computeIfAbsent(key, k -> new HashSet<>()).add(p.left);
                }
            }
            return new ReverseMaps(termToNT, pairToNT);
        }

        /** Simple immutable pair of non‑terminal ids. */
        public static final class Pair {
            final int first;
            final int second;

            Pair(int first, int second) {
                this.first = first;
                this.second = second;
            }

            @Override
            public boolean equals(Object o) {
                if (this == o) return true;
                if (!(o instanceof Pair)) return false;
                Pair p = (Pair) o;
                return first == p.first && second == p.second;
            }

            @Override
            public int hashCode() {
                return Objects.hash(first, second);
            }
        }

        /** Container for the reverse lookup structures. */
        public static final class ReverseMaps {
            final Map<String, Set<Integer>> termToNT;
            final Map<Pair, Set<Integer>> pairToNT;

            ReverseMaps(Map<String, Set<Integer>> termToNT,
                       Map<Pair, Set<Integer>> pairToNT) {
                this.termToNT = termToNT;
                this.pairToNT = pairToNT;
            }
        }
    }

    /** CYK parsing routine. Returns true iff the input string can be generated by the grammar. */
    public static boolean parse(String input, Grammar grammar) {
        // Tokenise: each character is a terminal symbol.
        String[] tokens = input.codePoints()
                               .mapToObj(cp -> new String(Character.toChars(cp)))
                               .toArray(String[]::new);
        int n = tokens.length;
        if (n == 0) {
            // CNF does not allow ε‑productions; reject empty string.
            return false;
        }

        Grammar.ReverseMaps rev = grammar.buildReverseMaps();
        int ntCount = grammar.nonTerminalCount();

        @SuppressWarnings("unchecked")
        Set<Integer>[][] table = new HashSet[n][n];
        for (int i = 0; i < n; i++) {
            table[i][i] = rev.termToNT.getOrDefault(tokens[i], Collections.emptySet());
        }

        // Fill upper triangle of the table.
        for (int span = 2; span <= n; span++) {          // length of the span
            for (int i = 0; i <= n - span; i++) {       // start of the span
                int j = i + span - 1;                   // end of the span
                Set<Integer> cell = new HashSet<>();
                for (int split = i; split < j; split++) {
                    Set<Integer> leftSet = table[i][split];
                    Set<Integer> rightSet = table[split + 1][j];
                    if (leftSet.isEmpty() || rightSet.isEmpty()) continue;
                    for (int B : leftSet) {
                        for (int C : rightSet) {
                            Grammar.Pair key = new Grammar.Pair(B, C);
                            Set<Integer> producers = rev.pairToNT.get(key);
                            if (producers != null) {
                                cell.addAll(producers);
                            }
                        }
                    }
                }
                table[i][j] = cell;
            }
        }

        return table[0][n - 1].contains(grammar.getStartSymbolId());
    }
}
